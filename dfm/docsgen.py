"""Generate the reference docs that must match the code.

    python -m dfm.docsgen          # rewrite docs/config.md and docs/cli.md
    python -m dfm.docsgen --check  # exit 1 if either is out of date (CI / tests)

`docs/config.md` comes from the pydantic config models (keys, types, defaults, and the
comments next to each field); `docs/cli.md` from every command's `--help`.
"""

from __future__ import annotations

import inspect
import re
import sys
from pathlib import Path
from typing import Any, Literal, get_args, get_origin

from pydantic import BaseModel
from typer.main import get_command
from typer.testing import CliRunner

from dfm.config import model as config_model
from dfm.config.model import DFMConfig

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
HEADER = "<!-- Generated by `python -m dfm.docsgen`; do not edit by hand. -->\n\n"


def _field_comments(cls: type[BaseModel]) -> dict[str, str]:
    """Comments written next to (or right above) each field in the model's source."""
    try:
        source = inspect.getsource(cls)
    except (OSError, TypeError):
        return {}
    comments: dict[str, str] = {}
    pending: list[str] = []
    for line in source.splitlines()[1:]:
        stripped = line.strip()
        if stripped.startswith("#"):
            pending.append(stripped.lstrip("# "))
            continue
        match = re.match(r"(\w+)\s*:\s*[^=]+(?:=\s*.*?)?(?:#\s*(.*))?$", stripped)
        if match:
            text = " ".join([*pending, match.group(2) or ""]).strip()
            if text:
                comments[match.group(1)] = text
        pending = []
    return comments


def _type_name(annotation: Any) -> str:
    if get_origin(annotation) is Literal:
        return "one of " + ", ".join(f"`{a}`" for a in get_args(annotation))
    return getattr(annotation, "__name__", None) or str(annotation).replace("typing.", "")


def _rows(cls: type[BaseModel], prefix: str, out: list[tuple[str, str, str, str]]) -> None:
    comments = _field_comments(cls)
    instance = cls()
    for name, info in cls.model_fields.items():
        value = getattr(instance, name)
        key = f"{prefix}{name}"
        if isinstance(value, BaseModel):
            _rows(type(value), key + ".", out)
            continue
        out.append(
            (
                key,
                _type_name(info.annotation),
                repr(value).replace("'", '"'),
                comments.get(name, ""),
            )
        )


def config_reference() -> str:
    rows: list[tuple[str, str, str, str]] = []
    _rows(DFMConfig, "", rows)
    lines = [
        HEADER + "# Configuration reference\n",
        "User config: `~/.config/dfm/config.toml`. A repository may add `.dfm/config.toml`, which can only",
        "**tighten** network and security settings and can never choose models (`dfm config show` lists",
        "where each effective value came from). CLI flags (`--offline`, `--local-models`) apply last.\n",
        "Network rules are `allow`, `ask` or `deny`; `ask` with no interactive terminal means `deny`.\n",
        "| Key | Type | Default | Notes |",
        "|---|---|---|---|",
    ]
    for key, kind, default, note in rows:
        lines.append(f"| `{key}` | {kind} | `{default}` | {note} |")
    sections = [n for n in DFMConfig.model_fields]
    lines.append(f"\nSections: {', '.join(f'`[{s}]`' for s in sections)}.")
    lines.append(f"\nSource of truth: `dfm/config/model.py` ({config_model.__name__}).")
    return "\n".join(lines) + "\n"


def _commands() -> list[list[str]]:
    from dfm.cli.app import app

    root = get_command(app)
    found: list[list[str]] = []
    for name, command in sorted(getattr(root, "commands", {}).items()):
        found.append([name])
        for sub in sorted(getattr(command, "commands", {}) or {}):
            found.append([name, sub])
    return found


def cli_reference() -> str:
    from dfm.cli.app import app

    runner = CliRunner()
    parts = [HEADER + "# Command reference\n", "Every `dfm` command, from its own `--help`.\n"]
    top = runner.invoke(
        app, ["--help"], env={"COLUMNS": "100", "NO_COLOR": "1", "TERM": "dumb"}, terminal_width=100
    )
    parts.append("## dfm\n\n```text\n" + _plain(top.output) + "\n```\n")
    for argv in _commands():
        result = runner.invoke(
            app,
            [*argv, "--help"],
            env={"COLUMNS": "100", "NO_COLOR": "1", "TERM": "dumb"},
            terminal_width=100,
        )
        parts.append(f"## dfm {' '.join(argv)}\n\n```text\n" + _plain(result.output) + "\n```\n")
    return "\n".join(parts)


def _plain(text: str) -> str:
    text = re.sub(r"\x1b\[[0-9;]*m", "", text)
    return "\n".join(line.rstrip() for line in text.strip().splitlines())


TARGETS = {"config.md": config_reference, "cli.md": cli_reference}


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale: list[str] = []
    for name, build in TARGETS.items():
        path = DOCS / name
        text = build()
        current = path.read_text() if path.exists() else ""
        if current != text:
            if check:
                stale.append(name)
            else:
                path.write_text(text)
                print(f"wrote docs/{name}")
    if stale:
        print(f"out of date: {', '.join('docs/' + s for s in stale)} (run `python -m dfm.docsgen`)")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
