@pytest.mark.skipif(shutil.which("protoc") is None, reason="protoc not installed")
async def test_edit_goes_to_the_proto_and_codegen_runs(home: Path, proto_repo: Path) -> None:
    hand_edit = {
        "action": "patch",
        "reason": "add the field to the generated module",
        "path": "gen/calc_pb2.py",
        "search": "calc.proto",
        "replace": "calc.proto units",
    }
    proto_edit = {
        "action": "patch",
        "reason": "add the field to the schema",
        "path": "proto/calc.proto",
        "search": "  double value = 1;\n",
        "replace": "  double value = 1;\n  string units = 2;\n",
    }
    regenerate = {"action": "run", "reason": "regenerate", "command": "make generate"}
    coder = ScriptedCoder(hand_edit, proto_edit, regenerate, DONE)
    rt = Runtime.create(proto_repo, request="add units to Reading", mode="implement")
    result = await implement(
        rt, "add a units field to Reading", ImplementOptions(coder=coder, max_steps=6)
    )
    await rt.close(result.outcome.session_status)
    assert result.outcome.status == "completed", result.outcome.report()
    assert any(
        "refused: gen/calc_pb2.py is generated" in p and "make generate" in p for p in coder.prompts
    )
    assert "string units = 2;" in (proto_repo / "proto/calc.proto").read_text()
    assert b"units" in (proto_repo / "gen/calc_pb2.py").read_bytes()  # regenerated by protoc
    assert (
        "calc.proto units" not in (proto_repo / "gen/calc_pb2.py").read_text()
    )  # hand edit refused


@pytest.mark.skipif(shutil.which("protoc") is None, reason="protoc not installed")
async def test_explicit_override_allows_the_edit(home: Path, proto_repo: Path) -> None:
    edit = {
        "action": "patch",
        "reason": "hotfix",
        "path": "gen/calc_pb2.py",
        "search": "# source: calc.proto",  # unique: the name also appears in the descriptor
        "replace": "# source: calc.proto (units)",
    }
    rt = Runtime.create(proto_repo, request="hotfix", mode="implement")
    result = await implement(
        rt,
        "hotfix",
        ImplementOptions(coder=ScriptedCoder(edit, DONE), max_steps=3, allow_generated_edits=True),
    )
    await rt.close(result.outcome.session_status)
    assert "gen/calc_pb2.py" in result.outcome.changed
