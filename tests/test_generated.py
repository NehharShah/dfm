def info(repo: Path, rel: str):  # type: ignore[no-untyped-def]
    return generated_info(repo / rel, repo)


def test_detection(tmp_path: Path) -> None:
    repo = fx.write(
        tmp_path / "r",
        {
            "api/user.pb.go": "// Code generated by protoc-gen-go. DO NOT EDIT.\n// source: proto/user.proto\npackage api\n",
            "proto/user.proto": PROTO,
            "db/models.go": "// Code generated by sqlc. DO NOT EDIT.\npackage db\n",
            "db/query.sql": "-- name: GetUser :one\nselect 1;\n",
            "sqlc.yaml": "version: '2'\n",
            "web/types.ts": "// @generated by graphql-codegen\nexport type A = 1;\n",
            "codegen.yml": "schema: schema.graphql\n",
            "py/calc_pb2.py": "x = 1\n",  # no header: the file name says it
            "vendor/thing.js": "var x;\n",
            ".gitattributes": "vendor/** linguist-generated\n",
            "src/app.py": "print('hand written')\n",
        },
    )
    go = info(repo, "api/user.pb.go")
    assert go is not None and go.sources == ["proto/user.proto"] and "DO NOT EDIT" in go.reason
    sqlc = info(repo, "db/models.go")
    assert (
        sqlc is not None
        and sqlc.regenerate == ("sqlc", "generate")
        and sqlc.sources == ["db/query.sql"]
    )
    gql = info(repo, "web/types.ts")
    assert gql is not None and "codegen.yml" in gql.sources
    named = info(repo, "py/calc_pb2.py")
    assert named is not None and named.reason == "codegen file name"
    assert info(repo, "vendor/thing.js") is not None
    assert info(repo, "src/app.py") is None


def test_regeneration_commands(tmp_path: Path) -> None:
    repo = fx.write(
        tmp_path / "r",
        {
            "proto/calc.proto": PROTO,
            "gen/calc_pb2.py": "# Generated by the protocol buffer compiler.  DO NOT EDIT!\n",
            "Makefile": "test:\n\tpytest\n\ngenerate:\n\tprotoc -Iproto --python_out=gen proto/calc.proto\n",
        },
    )
    assert info(repo, "gen/calc_pb2.py").regenerate == ("make", "generate")  # type: ignore[union-attr]
    (repo / "Makefile").unlink()
    guess = info(repo, "gen/calc_pb2.py")
    assert guess is not None and guess.regenerate == (
        "protoc",
        "-Iproto",
        "--python_out=gen",
        "proto/calc.proto",
    )
    (repo / "buf.gen.yaml").write_text("version: v2\n")
    assert info(repo, "gen/calc_pb2.py").regenerate == ("buf", "generate")  # type: ignore[union-attr]
    assert "edit proto/calc.proto then run `buf generate`" in info(repo, "gen/calc_pb2.py").advice()  # type: ignore[union-attr]


