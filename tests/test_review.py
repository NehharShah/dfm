def test_parse_diff_line_numbers() -> None:
    changes = {c.path: c for c in parse_diff(DIFF)}
    app_change = changes["src/app.py"]
    assert app_change.added == [
        (2, "def run(cmd):  # TODO handle errors"),
        (3, "    subprocess.run(cmd, shell=True)"),
        (12, '    print("debugging", x)'),
        (13, "    requests.get(url, verify=False)"),
    ]
    assert changes["config.py"].new_file
    assert changes["logo.png"].binary


def test_deterministic_checks() -> None:
    findings = deterministic_findings(parse_diff(DIFF), None)
    titles = {(f.title, f.file, f.line) for f in findings}
    assert ("subprocess with shell=True", "src/app.py", 3) in titles
    assert ("TLS verification disabled", "src/app.py", 13) in titles
    assert ("debug output left in", "src/app.py", 12) in titles
    assert ("new TODO", "src/app.py", 2) in titles
    assert ("possible secret added", "config.py", 1) in titles
    assert ("CI permissions widened", ".github/workflows/ci.yml", 2) in titles
    assert ("generated file edited by hand", "gen/api_pb2.py", 2) in titles
    assert ("lockfile changed without a manifest change", "uv.lock", None) in titles
    assert ("binary file changed", "logo.png", None) in titles
    assert ("source changed without test changes", None, None) in titles
    secret = next(f for f in findings if f.title == "possible secret added")
    assert "sk-" not in secret.evidence and secret.severity == "HIGH"


def test_clean_diff_has_no_serious_findings() -> None:
    clean = (
        "diff --git a/src/m.py b/src/m.py\n--- a/src/m.py\n+++ b/src/m.py\n@@ -1,1 +1,1 @@\n"
        "-def f(x): return x\n+def f(x: int) -> int:\n"
        "diff --git a/tests/test_m.py b/tests/test_m.py\n--- a/tests/test_m.py\n+++ b/tests/test_m.py\n"
        "@@ -1,1 +1,2 @@\n def test_f(): pass\n+def test_g(): pass\n"
    )
    findings = deterministic_findings(parse_diff(clean), None)
    assert not [f for f in findings if f.severity in {"BLOCKER", "HIGH", "MEDIUM"}]


async def test_model_findings_are_verified(tmp_path: Path) -> None:
    repo = fx.write(tmp_path / "r", {"src/calc.py": "def add(a, b):\n    return a - b\n"})
    diff = (
        "diff --git a/src/calc.py b/src/calc.py\n--- a/src/calc.py\n+++ b/src/calc.py\n"
        "@@ -1,2 +1,2 @@\n def add(a, b):\n-    return a + b\n+    return a - b\n"
    )
    findings = {
        "findings": [
            {
                "severity": "HIGH",
                "file": "src/calc.py",
                "line": 2,
                "title": "add subtracts",
                "evidence": "return a - b",
                "reasoning": "add returns a difference",
                "category": "correctness",
            },
            {
                "severity": "BLOCKER",
                "file": "src/calc.py",
                "line": 2,
                "title": "SQL injection",
                "evidence": "cursor.execute(query % user)",
                "reasoning": "invented",
                "category": "security",
            },
            {
                "severity": "MEDIUM",
                "file": "src/calc.py",
                "line": 40,
                "title": "wrong line",
                "evidence": "return a - b",
                "reasoning": "line out of range",
                "category": "correctness",
            },
            {
                "severity": "LOW",
                "file": "src/other.py",
                "line": 1,
                "title": "unknown file",
                "evidence": "x",
                "reasoning": "not in diff",
                "category": "tests",
            },
        ]
    }
    report = await review(None, diff, repo=repo, model=ScriptedCoder(findings))
    model_titles = [f.title for f in report.findings if f.source == "model"]
    assert model_titles == ["add subtracts"]
    assert report.dropped == 3
    assert "3 model finding(s) dropped" in report.render()


async def test_review_with_runtime_reports_architecture(
    home: Path, git_repo: Path, git: Callable[..., str]
) -> None:
    fx.write(
        git_repo,
        {
            "pyproject.toml": "[project]\nname = 'x'\n",
            "src/core/__init__.py": "",
            "src/core/model.py": "V = 1\n",
            "tests/__init__.py": "",
            "tests/test_model.py": "from src.core import model\n",
        },
    )
    git(git_repo, "add", ".")
    git(git_repo, "commit", "-qm", "base")
    (git_repo / "src" / "core" / "model.py").write_text("from tests import test_model\nV = 1\n")
    diff = git(git_repo, "diff")
    rt = Runtime.create(git_repo, request="review", mode="review")
    report = await review(rt, diff)
    await rt.close("completed")
    assert report.architecture and "src/core -> tests" in report.architecture
    assert any(f.category == "architecture" and f.severity == "MEDIUM" for f in report.findings)
    assert any("no local coding model" in n for n in report.notes)


def test_cli_review_from_stdin(home: Path, git_repo: Path) -> None:
    result = CliRunner().invoke(
        app, ["review", "--repo", str(git_repo), "--json", "--stdin"], input=DIFF
    )
    assert result.exit_code == 1  # HIGH findings present
    payload = json.loads(result.stdout)
    assert any(f["title"] == "possible secret added" for f in payload["findings"])
    assert "sk-abcdefghij" not in result.stdout


def test_cli_without_stdin_flag_reviews_git_even_when_not_a_tty(home: Path, git_repo: Path) -> None:
    # CI: stdin is an empty pipe. Reading it would review nothing and report "no findings".
    (git_repo / "app.py").write_text("def add(a, b):\n    return a - b  # changed\n")
    result = CliRunner().invoke(app, ["review", "--repo", str(git_repo), "--json"], input="")
    assert result.exit_code in (0, 1), result.output
    assert "app.py" in json.loads(result.stdout)["files"]
    bad = CliRunner().invoke(app, ["review", "--repo", str(git_repo), "--base", "no-such-ref"])
    assert bad.exit_code == 2 and "git diff failed" in bad.output
